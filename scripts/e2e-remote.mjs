import { createClient } from '@supabase/supabase-js';
import fs from 'fs';
import ws from 'ws';
const env = Object.fromEntries(fs.readFileSync('.env.local','utf8').trim().split('\n').map(l=>l.split('=')));
const sb = createClient(env.VITE_SUPABASE_URL, env.VITE_SUPABASE_ANON_KEY, { realtime: { transport: ws } });
const inv = (body) => sb.functions.invoke('game', { body }).then(r => r.error ? { err: r.error.message } : r.data);
const email = `e2e-test-${Date.now()}@example.com`;
console.log('wrong pw register:', (await inv({ op:'register', access:'yanlis', email, password:'gizli1234', name:'Test', prof:'hamal' })).error);
const c = await inv({ op:'candidates', access: process.env.IMPARATORLUK_ACCESS_PASSWORD });
console.log('candidates:', Array.isArray(c) ? c.length : c);
console.log('register:', JSON.stringify(await inv({ op:'register', access: process.env.IMPARATORLUK_ACCESS_PASSWORD, email, password:'gizli1234', name:'E2E Test', prof:'hamal' })));
const li = await sb.auth.signInWithPassword({ email, password:'gizli1234' }); console.log('login:', li.error?.message ?? 'ok');
console.log('me:', JSON.stringify(await inv({ op:'me' })).slice(0,80));
const hb = await inv({ op:'heartbeat' }); console.log('heartbeat: day', hb.world?.day, 'treasury', hb.world?.treasury, 'people', hb.world?.people?.length, hb.err ?? '');
console.log('act:', JSON.stringify(await inv({ op:'act', action:{ t:'eat' } })));
console.log('chat:', JSON.stringify(await inv({ op:'chat', text:'test amk', to:null })));
const { data: msgs } = await sb.from('messages').select('text'); console.log('messages via RLS:', JSON.stringify(msgs));
console.log('admin (non-founder):', JSON.stringify(await inv({ op:'admin', req:{ t:'snapshot' } })));
console.log('EMAIL', email);
